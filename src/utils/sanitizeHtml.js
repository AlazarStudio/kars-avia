import DOMPurify from "dompurify";

// Любой HTML с сервера (уведомления, журналы, описания из редактора) выводится
// только через эту функцию. Бэк подставляет в такой HTML имена и другие поля,
// которые пользователи вводят сами, без экранирования — вывод без очистки
// превращается в хранимый XSS (аудит 152-ФЗ, U4). `target` оставляем ради
// ссылок из редактора, которые открываются в новой вкладке (rel у них свой).
export const sanitizeHtml = (html) =>
  DOMPurify.sanitize(html ?? "", { ADD_ATTR: ["target"] });
