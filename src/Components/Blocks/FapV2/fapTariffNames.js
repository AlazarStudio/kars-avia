/**
 * Ключ сравнения названий тарифов.
 *
 * Тарифы в ФАП не хранятся объектами: список восстанавливается из строк отчёта, и
 * единственная связь строки с тарифом гостиницы или договора — СОВПАДЕНИЕ ИМЕНИ.
 * Поэтому сравнивать имена надо приведёнными, причём с обеих сторон.
 *
 * ⚠️ Замер стенда 15.08.2026, гостиница «Азия» (Абакан): у трёх видов номеров
 * название с хвостовым пробелом — «Стандарт SGL », «Стандарт DBL », «Стандарт TWIN ».
 * Восстановление обрезало имя строки, а имя тарифа гостиницы сравнивало как есть,
 * совпадения не находило и заводило ручной тариф-двойник с нулевыми ценами: гость
 * съезжал на него, и проживание считалось по нулю вместо 4788 ₽ за сутки. Дубль при
 * этом уходил в базу теневыми строками и воспроизводился при каждом входе.
 *
 * Регистр и повторные пробелы внутри тоже гасим: это тот же класс расхождения между
 * карточкой гостиницы и сохранённой строкой, и различать по ним два разных тарифа
 * в отчёте всё равно нельзя — на экране они выглядят одинаково.
 */
export const tariffNameKey = (value) =>
  String(value ?? "")
    .trim()
    .replace(/\s+/g, " ")
    .toLowerCase();

/** Есть ли в списке тариф с таким же именем (по правилам tariffNameKey). */
export const findTariffByName = (list, name) => {
  const key = tariffNameKey(name);
  if (!key) return null;
  return (list ?? []).find((t) => tariffNameKey(t?.name) === key) ?? null;
};
